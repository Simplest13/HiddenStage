import { expect, test } from '@playwright/test'

test('customer can sign in, complete onboarding, create a multi-service event, and view its details', async ({ page }) => {
  test.setTimeout(60000)
  await page.goto('/auth/login')
  await page.getByLabel('Email address').fill('demo@hiddenstage.test')
  await page.getByLabel('Password').fill('Preview123!')
  await page.getByRole('button', { name: 'Sign in' }).click()
  await expect(page).toHaveURL(/\/onboarding\/customer$/)

  await page.getByLabel('Phone number').fill('9876543210')
  await page.getByRole('button', { name: 'Continue' }).click()
  await page.getByLabel('PIN code').fill('560038')
  await page.getByLabel('Locality').fill('Indiranagar')
  await page.getByLabel('City').fill('Bengaluru')
  await page.getByLabel('State').fill('Karnataka')
  await page.getByRole('button', { name: 'Complete profile' }).click()
  await page.getByRole('button', { name: 'Go to your dashboard' }).click()
  await page.setViewportSize({ width: 390, height: 844 })
  await page.getByRole('button', { name: 'Open navigation' }).click()
  const customerNavigation = page.getByRole('navigation', { name: 'Your workspace navigation' })
  await expect(customerNavigation.getByRole('link', { name: 'Event requests' })).toBeVisible()
  await customerNavigation.getByRole('link', { name: 'Overview' }).click()
  await expect(page.getByRole('heading', { name: /welcome, demo/i })).toBeVisible()
  await expect(page.getByRole('heading', { name: /your first event begins/i })).toBeVisible()

  await page.getByRole('link', { name: /create an event/i }).click()
  await page.getByLabel('Event name').fill('A garden dinner')
  await page.getByLabel('Event type').selectOption('Family gathering')
  await page.getByLabel('Event description').fill('An intimate garden dinner with family and friends.')
  await page.getByLabel('Event date').fill('2030-06-20')
  await page.getByLabel('Expected guests').fill('24')
  await page.getByLabel('Start time').fill('17:00')
  await page.getByLabel('End time').fill('21:00')
  await page.getByRole('button', { name: 'Continue to location' }).click()

  await page.getByLabel('PIN code').fill('560038')
  await page.getByLabel('Locality').fill('Indiranagar')
  await page.getByLabel('City').fill('Bengaluru')
  await page.getByLabel('State').fill('Karnataka')
  await page.getByLabel('Venue name').fill('Garden venue')
  await page.getByLabel('Full venue address').fill('12 Main Road, Indiranagar')
  await page.getByRole('button', { name: 'Continue to requirements' }).click()

  await page.getByLabel('Service category').selectOption('food-and-drink')
  await page.getByLabel('Requirement title').fill('Vegetarian dinner catering')
  await page.getByLabel('Detailed description').fill('Dinner catering with vegetarian options for 24 guests.')
  await page.getByLabel('Individual budget (INR, optional)').fill('25000')
  await page.getByRole('button', { name: 'Add requirement' }).click()
  await page.getByRole('button', { name: 'Edit' }).click()
  await page.getByLabel('Requirement title').fill('Updated vegetarian dinner catering')
  await page.getByLabel('Detailed description').fill('Updated dinner catering with vegetarian options for 24 guests.')
  await page.getByRole('button', { name: 'Save requirement' }).click()
  await expect(page.getByText('Updated dinner catering with vegetarian options for 24 guests.')).toBeVisible()
  await page.getByLabel('Service category').selectOption('music-and-performance')
  await page.getByLabel('Requirement title').fill('Welcome hour acoustic music')
  await page.getByLabel('Detailed description').fill('Acoustic music for the welcome hour and guest arrival.')
  await page.getByRole('button', { name: 'Add requirement' }).click()
  await expect(page.getByRole('heading', { name: 'Welcome hour acoustic music' })).toBeVisible()
  await page.locator('.requirement-card').filter({ hasText: 'Welcome hour acoustic music' }).getByRole('button', { name: 'Remove' }).click()
  await expect(page.getByRole('heading', { name: 'Welcome hour acoustic music' })).toHaveCount(0)
  await page.getByLabel('Service category').selectOption('music-and-performance')
  await page.getByLabel('Requirement title').fill('Welcome hour acoustic music')
  await page.getByLabel('Detailed description').fill('Acoustic music for the welcome hour and guest arrival.')
  await page.getByRole('button', { name: 'Add requirement' }).click()
  await page.getByRole('button', { name: 'Continue to attachments' }).click()
  await page.getByLabel('Add reference files').setInputFiles({ name: 'notes.txt', mimeType: 'text/plain', buffer: Buffer.from('not allowed') })
  await expect(page.getByRole('alert')).toContainText('not an accepted file type')
  await page.getByLabel('Add reference files').setInputFiles({ name: 'venue-layout.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-1.4 demo') })
  await expect(page.getByText('venue-layout.pdf')).toBeVisible()
  await page.getByRole('button', { name: 'Continue to review' }).click()

  await expect(page.getByText('Updated dinner catering with vegetarian options for 24 guests.')).toBeVisible()
  await expect(page.getByText('Acoustic music for the welcome hour and guest arrival.')).toBeVisible()
  await expect(page.getByText(/venue-layout.pdf/)).toBeVisible()
  await page.locator('input[name="confirmDemo"]').check()
  await page.getByRole('button', { name: 'Confirm and save demo event' }).click()
  await expect(page.getByRole('heading', { name: /event plan is off to a thoughtful start/i })).toBeVisible()
  await page.getByRole('link', { name: 'View event details' }).click()
  await expect(page.getByRole('heading', { name: 'A garden dinner' })).toBeVisible()
  await expect(page.getByText(/Matching and invitation actions update local demo records only/)).toBeVisible()
  await page.getByRole('link', { name: 'Find professionals' }).first().click()
  await expect(page.getByRole('heading', { name: /professionals for A garden dinner/i })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'No eligible professionals found' })).toBeVisible()
  await page.goBack()
  await expect(page.getByRole('heading', { name: 'A garden dinner' })).toBeVisible()
  await expect(page.getByText(/Created:/)).toBeVisible()
  await expect(page.getByText(/Updated:/)).toBeVisible()

  await page.getByRole('link', { name: 'Edit event' }).click()
  await expect(page).toHaveURL(/\/app\/events\/[^/]+\/edit$/)
  await page.getByLabel('Event name').fill('A garden dinner, revised')
  await page.getByRole('button', { name: 'Continue to location' }).click()
  await page.getByRole('button', { name: 'Continue to requirements' }).click()
  await page.getByRole('button', { name: 'Continue to attachments' }).click()
  await page.getByRole('button', { name: 'Continue to review' }).click()
  await page.getByLabel(/I understand this is a demo request/).check()
  await page.getByRole('button', { name: 'Save event changes' }).click()
  await page.getByRole('link', { name: 'View event details' }).click()
  await expect(page.getByRole('heading', { name: 'A garden dinner, revised' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'A garden dinner, revised' })).toBeVisible()
  await page.getByRole('link', { name: /my events/i }).click()
  await expect(page).toHaveURL(/\/app\/events$/)
  await page.getByLabel('Search events').fill('garden dinner')
  await page.getByLabel('Event type').selectOption('Family gathering')
  await expect(page.getByRole('heading', { name: 'A garden dinner, revised' })).toBeVisible()
  await page.getByLabel('Search events').fill('no matching event')
  await expect(page.getByRole('heading', { name: 'No events match these filters' })).toBeVisible()
  await page.getByRole('button', { name: 'Clear filters' }).click()
  await expect(page.getByRole('heading', { name: 'A garden dinner, revised' })).toBeVisible()
  await page.goto('/app')
  await expect(page.locator('.dashboard-stat > strong')).toHaveText(['1', '1', '0', '0'])
})
