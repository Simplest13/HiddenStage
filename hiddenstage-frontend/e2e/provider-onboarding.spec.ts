import { expect, test } from '@playwright/test'

test('independent professional can register and complete a multi-location demo profile', async ({ page }) => {
  await page.goto('/auth/register')
  await page.getByLabel('Full name').fill('Rae Professional')
  await page.getByLabel('I am joining as').selectOption('PROVIDER')
  await page.getByLabel('Email address').fill('rae@example.test')
  await page.getByLabel('New password').fill('Preview123!')
  await page.getByLabel('Confirm password').fill('Preview123!')
  await page.getByLabel(/I agree to the/).check()
  await page.getByRole('button', { name: 'Create account' }).click()
  await page.getByRole('button', { name: 'Continue with demo verification' }).click()
  await page.getByRole('link', { name: 'Continue to onboarding' }).click()
  await expect(page).toHaveURL(/\/onboarding\/provider$/)

  await page.getByLabel('Professional or display name').fill('Rae Studio')
  await page.getByLabel('Short description').fill('Thoughtful photography and styling for intimate celebrations.')
  await page.getByLabel('Contact phone or email').fill('rae@example.test')
  await page.getByLabel('Photography').check()
  await page.getByLabel('Decor & styling').check()
  await page.getByLabel('PIN code').nth(0).fill('560038')
  await page.getByLabel('Locality').nth(0).fill('Indiranagar')
  await page.getByLabel('City').nth(0).fill('Bengaluru')
  await page.getByLabel('State').nth(0).fill('Karnataka')
  await page.getByRole('button', { name: 'Add coverage location' }).click()
  await page.getByLabel('PIN code').nth(1).fill('560001')
  await page.getByLabel('Locality').nth(1).fill('Central Bengaluru')
  await page.getByLabel('City').nth(1).fill('Bengaluru')
  await page.getByLabel('State').nth(1).fill('Karnataka')
  await page.getByRole('button', { name: 'Save and continue' }).click()
  await expect(page.getByRole('heading', { name: /profile is ready/i })).toBeVisible()
  await page.getByRole('button', { name: 'Continue to professional workspace' }).click()
  await expect(page).toHaveURL(/\/app\/provider$/)
  await expect(page.getByRole('heading', { name: 'Welcome, Rae Studio' })).toBeVisible()
  await page.getByRole('link', { name: 'Manage services' }).click()
  await page.getByLabel('Service category').selectOption('event-hosting')
  await page.getByLabel('Service title').fill('Celebration hosting')
  await page.getByLabel('Service description').fill('Friendly hosting for a family celebration.')
  await page.getByLabel('Optional base price (INR)').fill('12000')
  await page.getByRole('button', { name: 'Add service' }).click()
  await expect(page.getByRole('heading', { name: 'Celebration hosting' })).toBeVisible()
  const providerNavigation = page.getByRole('navigation', { name: 'Your workspace navigation' })
  await providerNavigation.getByRole('link', { name: 'Service coverage' }).click()
  await page.getByLabel('PIN code').fill('560099')
  await page.getByLabel('Locality').fill('South Bengaluru')
  await page.getByLabel('City').fill('Bengaluru')
  await page.getByLabel('State').fill('Karnataka')
  await page.getByRole('button', { name: 'Add coverage' }).click()
  await expect(page.getByText('South Bengaluru, Bengaluru')).toBeVisible()
  await providerNavigation.getByRole('link', { name: 'Invitations' }).click()
  await expect(page.getByRole('heading', { name: 'No invitations here' })).toBeVisible()
})
