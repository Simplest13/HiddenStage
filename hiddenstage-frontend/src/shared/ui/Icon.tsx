export type IconName = keyof typeof iconComponents

export function Icon({
  name,
  size = 18,
  color = 'currentColor',
  className,
  style,
}: {
  name: IconName
  size?: number
  color?: string
  className?: string
  style?: CSSProperties
}) {
  const IconComponent = iconComponents[name]
  return <IconComponent size={size} color={color} className={className} style={style} aria-hidden="true" focusable="false" />
}
